import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { coreCommands, coreEntities, coreQueries } from "@/lib/school-api/registry";
import { getOpenApiSchemaName } from "@/lib/school-api/schemas/schema-name";

const repoRoot = resolve(import.meta.dirname, "../../../..");

function resolveOutputPath(flag: "--output" | "--dart-output", defaultPath: string): string {
  const outputIndex = process.argv.indexOf(flag);
  if (outputIndex === -1) {
    return defaultPath;
  }

  const requestedPath = process.argv[outputIndex + 1];
  if (!requestedPath) {
    throw new Error(`${flag} requires a file path`);
  }
  return resolve(process.cwd(), requestedPath);
}

const tsOutputPath = resolveOutputPath(
  "--output",
  resolve(repoRoot, "package/generated-api-client/src/generated/client-bindings.ts"),
);
const dartOutputPath = resolveOutputPath(
  "--dart-output",
  resolve(repoRoot, "../edaya_mobile/packages/edaya_api_client/lib/src/generated/client_bindings.dart"),
);

function formatObject(value: unknown, indent = 2): string {
  return JSON.stringify(value, null, indent)
    .split("\n")
    .map((line, index) => (index === 0 ? line : `${" ".repeat(2)}${line}`))
    .join("\n");
}

const entities = Object.fromEntries(
  coreEntities.map((entity) => {
    return [
      entity.serviceName,
      {
        publicName: entity.publicName,
        schemaName: getOpenApiSchemaName(entity.responseSchema),
        allowDirectSave: entity.allowDirectSave,
      },
    ];
  }),
);

const commands = Object.fromEntries(
  coreCommands.map((command) => {
    return [
      command.methodName,
      {
        publicName: command.publicName,
        requestSchemaName: getOpenApiSchemaName(command.requestSchema),
        responseSchemaName: getOpenApiSchemaName(command.responseSchema),
      },
    ];
  }),
);

const queries = Object.fromEntries(
  coreQueries.map((query) => {
    return [
      query.methodName,
      {
        publicName: query.publicName,
        requestSchemaName: getOpenApiSchemaName(query.requestSchema),
        responseSchemaName: getOpenApiSchemaName(query.responseSchema),
      },
    ];
  }),
);

const tsSource = `// This file is auto-generated by apps/api/src/scripts/generate-api-client.ts
// Do not edit manually.

export const clientBindings = {
  entities: ${formatObject(entities)},
  commands: ${formatObject(commands)},
  queries: ${formatObject(queries)},
} as const

export type ClientBindings = typeof clientBindings
`;

function dartString(value: string): string {
  return JSON.stringify(value);
}

function generateDartEntityMap(): string {
  const entries = Object.entries(entities).map(([key, binding]) => {
    return `    ${dartString(key)}: EntityBinding(
      publicName: ${dartString(binding.publicName)},
      schemaName: ${dartString(binding.schemaName)},
      allowDirectSave: ${binding.allowDirectSave},
    ),`;
  });
  return entries.join("\n");
}

function generateDartCommandMethods(): string {
  return Object.entries(commands).map(([key, binding]) => {
    return `  Future<Map<String, dynamic>> ${key}(Map<String, dynamic> payload) =>
      runCommand(${dartString(binding.publicName)}, payload);`;
  }).join("\n\n");
}

function generateDartQueryMethods(): string {
  return Object.entries(queries).map(([key, binding]) => {
    return `  Future<Map<String, dynamic>> ${key}(Map<String, dynamic> payload) =>
      runQuery(${dartString(binding.publicName)}, payload);`;
  }).join("\n\n");
}

function generateDartEntityGetters(): string {
  return Object.entries(entities).map(([key]) => {
    return `  EntityResource get ${key} => entities[${dartString(key)}]!;`;
  }).join("\n\n");
}

const dartSource = `// This file is auto-generated by apps/api/src/scripts/generate-api-client.ts
// Do not edit manually.

class EntityBinding {
  const EntityBinding({
    required this.publicName,
    required this.schemaName,
    required this.allowDirectSave,
  });

  final String publicName;
  final String schemaName;
  final bool allowDirectSave;
}

abstract final class ClientBindings {
  static const entities = <String, EntityBinding>{
${generateDartEntityMap()}
  };

  static const commands = <String, String>{
${Object.entries(commands).map(([key, binding]) => `    ${dartString(key)}: ${dartString(binding.publicName)},`).join("\n")}
  };

  static const queries = <String, String>{
${Object.entries(queries).map(([key, binding]) => `    ${dartString(key)}: ${dartString(binding.publicName)},`).join("\n")}
  };
}
`;

const dartSurfacePath = dartOutputPath.replace(
  /client_bindings\.dart$/,
  "school_client_surface.dart",
);

const dartSurfaceSource = `// This file is auto-generated by apps/api/src/scripts/generate-api-client.ts
// Do not edit manually.

import '../entity_resource.dart';
import '../school_client.dart';

extension GeneratedSchoolClientEntities on SchoolClient {
${generateDartEntityGetters()}
}

extension GeneratedSchoolClientCommands on SchoolClient {
${generateDartCommandMethods()}
}

extension GeneratedSchoolClientQueries on SchoolClient {
${generateDartQueryMethods()}
}
`;

mkdirSync(resolve(tsOutputPath, ".."), { recursive: true });
writeFileSync(tsOutputPath, tsSource);

mkdirSync(resolve(dartOutputPath, ".."), { recursive: true });
writeFileSync(dartOutputPath, dartSource);
writeFileSync(dartSurfacePath, dartSurfaceSource);

// eslint-disable-next-line no-console
console.log(`API client bindings generated at ${tsOutputPath}`);
// eslint-disable-next-line no-console
console.log(`Dart API client bindings generated at ${dartOutputPath}`);
// eslint-disable-next-line no-console
console.log(`Dart API client surface generated at ${dartSurfacePath}`);
