import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import type { z } from "@hono/zod-openapi";
import { coreCommands, coreEntities, coreQueries } from "@/lib/school-api/registry";

const outputPath = resolve(
  import.meta.dirname,
  "../../../../packages/api-client/src/generated/client-bindings.ts",
);

function getOpenApiSchemaName(schema: z.ZodTypeAny): string {
  let current: unknown = schema;

  while (current && typeof current === "object") {
    const def = (current as { _def?: Record<string, unknown> })._def;
    const openapi = def?.openapi as
      | { _internal?: { refId?: string }; metadata?: { refId?: string } }
      | undefined;

    const refId = openapi?._internal?.refId ?? openapi?.metadata?.refId;
    if (typeof refId === "string") {
      return refId;
    }

    if (typeof def?.innerType === "function") {
      current = (def.innerType as () => unknown)();
      continue;
    }

    if (typeof def?.getter === "function") {
      current = (def.getter as () => unknown)();
      continue;
    }

    if (def?.schema) {
      current = def.schema;
      continue;
    }

    break;
  }

  throw new Error("No OpenAPI schema name found on Zod schema");
}

function formatObject(value: unknown, indent = 2): string {
  return JSON.stringify(value, null, indent)
    .split("\n")
    .map((line, index) => (index === 0 ? line : `${" ".repeat(2)}${line}`))
    .join("\n");
}

const entities = Object.fromEntries(
  coreEntities.map((entity) => {
    return [
      entity.serviceName,
      {
        publicName: entity.publicName,
        schemaName: getOpenApiSchemaName(entity.responseSchema),
        allowDirectSave: entity.allowDirectSave,
      },
    ];
  }),
);

const commands = Object.fromEntries(
  coreCommands.map((command) => {
    return [
      command.methodName,
      {
        publicName: command.publicName,
        requestSchemaName: getOpenApiSchemaName(command.requestSchema),
        responseSchemaName: getOpenApiSchemaName(command.responseSchema),
      },
    ];
  }),
);

const queries = Object.fromEntries(
  coreQueries.map((query) => {
    return [
      query.methodName,
      {
        publicName: query.publicName,
        requestSchemaName: getOpenApiSchemaName(query.requestSchema),
        responseSchemaName: getOpenApiSchemaName(query.responseSchema),
      },
    ];
  }),
);

const source = `// This file is auto-generated by apps/api/src/scripts/generate-api-client.ts
// Do not edit manually.

export const clientBindings = {
  entities: ${formatObject(entities)},
  commands: ${formatObject(commands)},
  queries: ${formatObject(queries)},
} as const

export type ClientBindings = typeof clientBindings
`;

mkdirSync(resolve(outputPath, ".."), { recursive: true });
writeFileSync(outputPath, source);

// eslint-disable-next-line no-console
console.log(`API client bindings generated at ${outputPath}`);
