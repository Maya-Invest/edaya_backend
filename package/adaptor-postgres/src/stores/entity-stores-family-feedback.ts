import type {
  FamilyFeedbackCampaign,
  FamilyFeedbackCommentReadAudit,
  FamilyFeedbackResponse,
  FamilyFeedbackSlot,
  FamilyFeedbackSnapshot,
} from '@edaya/core'
import {
  FamilyFeedbackCampaign as FamilyFeedbackCampaignCtor,
  FamilyFeedbackCampaignStatus,
  FamilyFeedbackCommentReadAudit as FamilyFeedbackCommentReadAuditCtor,
  FamilyFeedbackResponse as FamilyFeedbackResponseCtor,
  FamilyFeedbackSlot as FamilyFeedbackSlotCtor,
  FamilyFeedbackSlotStatus,
  FamilyFeedbackSnapshot as FamilyFeedbackSnapshotCtor,
} from '@edaya/core'
import { deserializeJsonb } from '../lib/mappers'
import { customStore } from '../lib/store-factory'
import * as schema from '../postgres-schema'
import { enumValue } from './entity-store-helpers'

export function createFamilyFeedbackStores(db: any) {
  return {
    familyFeedbackCampaigns: customStore(
      db,
      schema.familyFeedbackCampaigns,
      (entity: FamilyFeedbackCampaign) => ({
        id: entity.id,
        schoolId: entity.schoolId,
        academicYearId: entity.academicYearId,
        academicPeriodId: entity.academicPeriodId,
        classGroupId: entity.classGroupId,
        classSubjectId: entity.classSubjectId,
        teacherAssignmentId: entity.teacherAssignmentId,
        teacherId: entity.teacherId,
        subjectId: entity.subjectId,
        questionVersion: entity.questionVersion,
        status: entity.status,
        opensAt: entity.opensAt ?? null,
        closesAt: entity.closesAt ?? null,
        openedAt: entity.openedAt ?? null,
        closedAt: entity.closedAt ?? null,
        cancelledAt: entity.cancelledAt ?? null,
        publishedAt: entity.publishedAt ?? null,
        archivedAt: entity.archivedAt ?? null,
        answersPurgedAt: entity.answersPurgedAt ?? null,
        moderatorStaffId: entity.moderatorStaffId ?? null,
        themeDraft: entity.themeDraft ?? null,
        createdAt: entity.createdAt,
        updatedAt: entity.updatedAt,
      }),
      (row: any) => new FamilyFeedbackCampaignCtor({
        id: row.id,
        schoolId: row.schoolId,
        academicYearId: row.academicYearId,
        academicPeriodId: row.academicPeriodId,
        classGroupId: row.classGroupId,
        classSubjectId: row.classSubjectId,
        teacherAssignmentId: row.teacherAssignmentId,
        teacherId: row.teacherId,
        subjectId: row.subjectId,
        questionVersion: row.questionVersion,
        status: enumValue(FamilyFeedbackCampaignStatus, row.status, 'familyFeedbackCampaigns.status'),
        opensAt: row.opensAt,
        closesAt: row.closesAt,
        openedAt: row.openedAt,
        closedAt: row.closedAt,
        cancelledAt: row.cancelledAt,
        publishedAt: row.publishedAt,
        archivedAt: row.archivedAt,
        answersPurgedAt: row.answersPurgedAt,
        moderatorStaffId: row.moderatorStaffId,
        themeDraft: row.themeDraft,
        createdAt: row.createdAt,
        updatedAt: row.updatedAt,
      }),
    ),
    familyFeedbackSlots: customStore(
      db,
      schema.familyFeedbackSlots,
      (entity: FamilyFeedbackSlot) => ({
        id: entity.id,
        schoolId: entity.schoolId,
        campaignId: entity.campaignId,
        studentId: entity.studentId,
        teacherAssignmentId: entity.teacherAssignmentId,
        status: entity.status,
        completingGuardianId: entity.completingGuardianId ?? null,
        completedAt: entity.completedAt ?? null,
        createdAt: entity.createdAt,
      }),
      (row: any) => new FamilyFeedbackSlotCtor({
        id: row.id,
        schoolId: row.schoolId,
        campaignId: row.campaignId,
        studentId: row.studentId,
        teacherAssignmentId: row.teacherAssignmentId,
        status: enumValue(FamilyFeedbackSlotStatus, row.status, 'familyFeedbackSlots.status'),
        completingGuardianId: row.completingGuardianId,
        completedAt: row.completedAt,
        createdAt: row.createdAt,
      }),
    ),
    familyFeedbackResponses: customStore(
      db,
      schema.familyFeedbackResponses,
      (entity: FamilyFeedbackResponse) => ({
        id: entity.id,
        schoolId: entity.schoolId,
        campaignId: entity.campaignId,
        slotId: entity.slotId,
        answers: entity.answers,
        comment: entity.comment ?? null,
        createdAt: entity.createdAt,
      }),
      (row: any) => new FamilyFeedbackResponseCtor({
        id: row.id,
        schoolId: row.schoolId,
        campaignId: row.campaignId,
        slotId: row.slotId,
        answers: deserializeJsonb(row.answers),
        comment: row.comment,
        createdAt: row.createdAt,
      }),
    ),
    familyFeedbackSnapshots: customStore(
      db,
      schema.familyFeedbackSnapshots,
      (entity: FamilyFeedbackSnapshot) => ({
        id: entity.id,
        schoolId: entity.schoolId,
        campaignId: entity.campaignId,
        payload: entity.payload,
        publishedAt: entity.publishedAt,
        publishedByStaffId: entity.publishedByStaffId,
      }),
      (row: any) => new FamilyFeedbackSnapshotCtor({
        id: row.id,
        schoolId: row.schoolId,
        campaignId: row.campaignId,
        payload: deserializeJsonb(row.payload),
        publishedAt: row.publishedAt,
        publishedByStaffId: row.publishedByStaffId,
      }),
    ),
    familyFeedbackCommentReadAudit: customStore(
      db,
      schema.familyFeedbackCommentReadAudit,
      (entity: FamilyFeedbackCommentReadAudit) => ({
        id: entity.id,
        schoolId: entity.schoolId,
        campaignId: entity.campaignId,
        actorId: entity.actorId,
        actorKind: entity.actorKind,
        subjectId: entity.subjectId,
        readAt: entity.readAt,
      }),
      (row: any) => new FamilyFeedbackCommentReadAuditCtor({
        id: row.id,
        schoolId: row.schoolId,
        campaignId: row.campaignId,
        actorId: row.actorId,
        actorKind: row.actorKind,
        subjectId: row.subjectId,
        readAt: row.readAt,
      }),
    ),
  }
}
