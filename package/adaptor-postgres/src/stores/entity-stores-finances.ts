import type { CatalogService, Payment, StudentCharge, StudentServiceEnrollment, StudentYearAccount } from '@edaya/core'
import type { StoreDatabase } from '../postgres-store'
import type { EntityStores } from './entity-stores-types'
import {
  CatalogServiceCategory,
  CatalogService as CatalogServiceCtor,
  CatalogServiceStatus,
  ChargeStatus,
  Payment as PaymentCtor,
  PaymentKind,
  PaymentMethod,
  PaymentStatus,
  ServiceEnrollmentSource,
  ServiceEnrollmentStatus,
  StudentCharge as StudentChargeCtor,
  StudentServiceEnrollment as StudentServiceEnrollmentCtor,
  StudentYearAccount as StudentYearAccountCtor,
} from '@edaya/core'
import { deserializeJsonb } from '../lib/mappers'
import { customStore } from '../lib/store-factory'
import * as schema from '../postgres-schema'
import { enumValue } from './entity-store-helpers'

export function createFinancesEntityStores(db: StoreDatabase): Pick<EntityStores, 'catalogServices' | 'studentServiceEnrollments' | 'studentCharges' | 'studentYearAccounts' | 'payments'> {
  return {
    catalogServices: customStore(
      db,
      schema.catalogServices,
      (entity: CatalogService) => ({
        id: entity.id,
        schoolId: entity.schoolId,
        academicYearId: entity.academicYearId,
        name: entity.name,
        shortName: entity.shortName,
        description: entity.description ?? null,
        category: entity.category,
        autoBilling: entity.autoBilling,
        billingKind: entity.billingKind,
        defaultPrice: entity.defaultPrice.amount,
        currency: entity.defaultPrice.currency,
        billingTerms: entity.billingTerms,
        status: entity.status,
        createdAt: entity.createdAt,
        updatedAt: entity.updatedAt ?? null,
      }),
      row => new CatalogServiceCtor({
        id: row.id,
        schoolId: row.schoolId,
        academicYearId: row.academicYearId,
        name: row.name,
        shortName: row.shortName ?? undefined,
        description: row.description,
        category: enumValue(CatalogServiceCategory, row.category, 'catalogServices.category'),
        autoBilling: deserializeJsonb(row.autoBilling),
        billingKind: 'one_time',
        defaultPrice: row.defaultPrice,
        currency: row.currency,
        billingTerms: deserializeJsonb(row.billingTerms),
        status: enumValue(CatalogServiceStatus, row.status, 'catalogServices.status'),
        createdAt: row.createdAt,
        updatedAt: row.updatedAt,
      }),
    ),

    studentServiceEnrollments: customStore(
      db,
      schema.studentServiceEnrollments,
      (entity: StudentServiceEnrollment) => ({
        id: entity.id,
        schoolId: entity.schoolId,
        studentId: entity.studentId,
        catalogServiceId: entity.catalogServiceId,
        academicYearId: entity.academicYearId,
        status: entity.status,
        source: entity.source,
        automation: entity.automation ?? null,
        acceptedTerms: {
          catalogServiceId: entity.acceptedTerms.catalogServiceId,
          name: entity.acceptedTerms.name,
          category: entity.acceptedTerms.category,
          currency: entity.acceptedTerms.currency,
          price: entity.acceptedTerms.price,
          billingKind: entity.acceptedTerms.billingKind,
          billingTerms: entity.acceptedTerms.billingTerms,
          installmentTemplates: entity.acceptedTerms.installmentTemplates,
        },
        enrolledAt: entity.enrolledAt,
        cancelledAt: entity.cancelledAt ?? null,
        cancellationReason: entity.cancellationReason ?? null,
        cancelledById: entity.cancelledById ?? null,
        createdAt: entity.createdAt,
        updatedAt: entity.updatedAt ?? null,
      }),
      row => new StudentServiceEnrollmentCtor({
        id: row.id,
        schoolId: row.schoolId,
        studentId: row.studentId,
        catalogServiceId: row.catalogServiceId,
        academicYearId: row.academicYearId,
        status: enumValue(ServiceEnrollmentStatus, row.status, 'studentServiceEnrollments.status'),
        source: enumValue(ServiceEnrollmentSource, row.source, 'studentServiceEnrollments.source'),
        automation: row.automation ? deserializeJsonb(row.automation) : undefined,
        acceptedTerms: deserializeJsonb(row.acceptedTerms),
        enrolledAt: row.enrolledAt,
        cancelledAt: row.cancelledAt,
        cancellationReason: row.cancellationReason,
        cancelledById: row.cancelledById,
        createdAt: row.createdAt,
        updatedAt: row.updatedAt,
      }),
    ),

    studentCharges: customStore(
      db,
      schema.studentCharges,
      (entity: StudentCharge) => ({
        id: entity.id,
        schoolId: entity.schoolId,
        studentId: entity.studentId,
        enrollmentId: entity.enrollmentId,
        academicYearId: entity.academicYearId,
        label: entity.label,
        expectedAmount: entity.expectedAmount.amount,
        allocatedAmount: entity.allocatedAmount.amount,
        adjustmentAmount: entity.adjustmentAmount.amount,
        adjustmentReason: entity.adjustmentReason ?? null,
        adjustedById: entity.adjustedById ?? null,
        adjustedAt: entity.adjustedAt ?? null,
        waiverAmount: entity.waiverAmount.amount,
        waiverReason: entity.waiverReason ?? null,
        waivedById: entity.waivedById ?? null,
        waivedAt: entity.waivedAt ?? null,
        currency: entity.currency,
        dueDate: entity.dueDate ?? null,
        status: entity.status,
        cancellationReason: entity.cancellationReason ?? null,
        cancelledById: entity.cancelledById ?? null,
        cancelledAt: entity.cancelledAt ?? null,
        installments: entity.installments,
        createdAt: entity.createdAt,
        updatedAt: entity.updatedAt ?? null,
      }),
      row => new StudentChargeCtor({
        id: row.id,
        schoolId: row.schoolId,
        studentId: row.studentId,
        enrollmentId: row.enrollmentId,
        academicYearId: row.academicYearId,
        label: row.label,
        expectedAmount: row.expectedAmount,
        allocatedAmount: row.allocatedAmount,
        adjustmentAmount: row.adjustmentAmount,
        adjustmentReason: row.adjustmentReason,
        adjustedById: row.adjustedById,
        adjustedAt: row.adjustedAt,
        waiverAmount: row.waiverAmount,
        waiverReason: row.waiverReason,
        waivedById: row.waivedById,
        waivedAt: row.waivedAt,
        currency: row.currency,
        dueDate: row.dueDate,
        status: enumValue(ChargeStatus, row.status, 'studentCharges.status'),
        cancellationReason: row.cancellationReason,
        cancelledById: row.cancelledById,
        cancelledAt: row.cancelledAt,
        installments: [...deserializeJsonb(row.installments)],
        createdAt: row.createdAt,
        updatedAt: row.updatedAt,
      }),
    ),

    studentYearAccounts: customStore(
      db,
      schema.studentYearAccounts,
      (entity: StudentYearAccount) => ({
        id: entity.id,
        schoolId: entity.schoolId,
        studentId: entity.studentId,
        academicYearId: entity.academicYearId,
        currency: entity.currency,
        availableBalance: entity.availableBalance.amount,
        createdAt: entity.createdAt,
        updatedAt: entity.updatedAt ?? null,
      }),
      row => new StudentYearAccountCtor({
        id: row.id,
        schoolId: row.schoolId,
        studentId: row.studentId,
        academicYearId: row.academicYearId,
        currency: row.currency,
        availableBalance: row.availableBalance,
        createdAt: row.createdAt,
        updatedAt: row.updatedAt,
      }),
    ),

    payments: customStore(
      db,
      schema.payments,
      (entity: Payment) => ({
        id: entity.id,
        schoolId: entity.schoolId,
        accountId: entity.accountId,
        academicYearId: entity.academicYearId,
        kind: entity.kind,
        amount: entity.amount.amount,
        currency: entity.amount.currency,
        paymentDate: entity.paymentDate,
        method: entity.method,
        status: entity.status,
        reference: entity.reference ?? null,
        notes: entity.notes ?? null,
        recordedById: entity.recordedById ?? null,
        reversesPaymentId: entity.reversesPaymentId ?? null,
        reversedByPaymentId: entity.reversedByPaymentId ?? null,
        reversedAt: entity.reversedAt ?? null,
        reversedById: entity.reversedById ?? null,
        createdAt: entity.createdAt,
      }),
      row => new PaymentCtor({
        id: row.id,
        schoolId: row.schoolId,
        accountId: row.accountId,
        academicYearId: row.academicYearId,
        kind: enumValue(PaymentKind, row.kind, 'payments.kind'),
        amount: row.amount,
        currency: row.currency,
        paymentDate: row.paymentDate,
        method: enumValue(PaymentMethod, row.method, 'payments.method'),
        status: enumValue(PaymentStatus, row.status, 'payments.status'),
        reference: row.reference,
        notes: row.notes,
        recordedById: row.recordedById,
        reversesPaymentId: row.reversesPaymentId,
        reversedByPaymentId: row.reversedByPaymentId,
        reversedAt: row.reversedAt,
        reversedById: row.reversedById,
        createdAt: row.createdAt,
      }),
    ),
  }
}
