import process from "node:process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Handlebars from "handlebars";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const templateKeys = [
  "report-card.v1",
  "annual-report-card.v1",
  "logbook.v1",
  "schooling-certificate.v1",
  "enrollment-record.v1",
  "student-id-card.v1",
  "invoice.v1",
  "receipt.v1",
  "settlement-quittance.v1",
  "account-statement.v1",
  "payment-reminder.v1",
  "withdrawal-certificate.v1",
  "annual-transcript.v1",
  "convocation.v1",
  "class-timetable.v1",
  "teacher-timetable.v1",
  "class-roster.v1",
  "attendance-sheet.v1",
  "incident-report.v1",
] as const;

for (const key of templateKeys) {
  const templateDir = join(root, "src/templates", key);
  const sourcePath = join(templateDir, "template.hbs");
  const outPath = join(templateDir, "template.precompiled.js");

  const source = readFileSync(sourcePath, "utf8").replaceAll("\r\n", "\n");
  const spec = Handlebars.precompile(source, {
    strict: false,
    knownHelpersOnly: false,
  });

  const expected = `/** Auto-generated by scripts/precompile-templates.ts — do not edit. */\nexport default ${spec}\n`;
  if (process.argv.includes("--check")) {
    const actual = existsSync(outPath) ? readFileSync(outPath, "utf8").replaceAll("\r\n", "\n") : "";
    if (actual !== expected)
      throw new Error(`Template drift: ${key}; run bun run repo generate templates`);
  }
  else {
    mkdirSync(templateDir, { recursive: true });
    writeFileSync(outPath, expected, "utf8");
    console.log(`precompiled ${key}`);
  }
}
